// bounds over all rings
let minLon = 999, maxLon = -999, minLat = 999, maxLat = -999;
for (const ring of polys)
  for (const [lon, lat] of ring) {
    if (lon < minLon) minLon = lon;
    if (lon > maxLon) maxLon = lon;
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
  }
const midLat = (minLat + maxLat) / 2;
const kx = Math.cos((midLat * Math.PI) / 180);
const W = 1000;
const PAD = 24;
const scale = (W - PAD * 2) / ((maxLon - minLon) * kx);
const H = Math.round((maxLat - minLat) * scale + PAD * 2);

const px = (lon) => +(PAD + (lon - minLon) * kx * scale).toFixed(1);
const py = (lat) => +(PAD + (maxLat - lat) * scale).toFixed(1);

// decimate: keep points at least `tol` px apart
function decimate(ring, tol = 1.6) {
  const out = [];
  let last = null;
  for (const [lon, lat] of ring) {
    const x = px(lon), y = py(lat);
    if (!last || Math.hypot(x - last[0], y - last[1]) >= tol) {
      out.push([x, y]);
      last = [x, y];
    }
  }
  return out;
}

const paths = [];
for (const ring of polys) {
  const pts = decimate(ring);
  if (pts.length < 8) continue; // skip specks
  paths.push("M" + pts.map(([x, y]) => `${x} ${y}`).join("L") + "Z");
}
